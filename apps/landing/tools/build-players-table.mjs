// Pre-renders the player table rows into players.html.
//
//   node tools/build-players-table.mjs
//
// Why this exists
// ---------------
// players.js builds the table client-side. That is fine for humans, but the
// player list is the page most likely to earn long-tail search traffic
// ("virat kohli auction base price"), and a crawler's first pass sees only an
// empty <tbody>. Google does render JavaScript, but in a deferred second wave
// that is not worth betting the page's indexing on.
//
// So the rows are generated into the HTML at build time. players.js still
// owns search / filter / sort at runtime and re-renders on first load, which
// produces byte-identical markup — the static rows are purely what the
// crawler (and a JS-less visitor) sees first.
//
// The player data and the price formatter are both read out of players.js
// rather than duplicated here, so the two can never drift apart. Re-run this
// whenever players.js changes.
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const LANDING = join(here, '..')
const PLAYERS_JS = join(LANDING, 'players.js')
const PLAYERS_HTML = join(LANDING, 'players.html')

const START = '<!-- players:start (generated by tools/build-players-table.mjs — do not edit by hand) -->'
const END = '<!-- players:end -->'

// Escape anything that would break out of the HTML we are generating. The
// current data is plain names, but a future entry with an apostrophe or an
// ampersand shouldn't be able to produce invalid markup.
const esc = (value) =>
    String(value)
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;')

// Pull `const players = [...]` and `function formatPrice(...)` straight out of
// the browser script. players.js can't simply be imported: it touches
// document/window at the top level and would throw under Node.
const extract = (source) => {
    const arrayMatch = source.match(/const\s+players\s*=\s*(\[[\s\S]*?\n\]);/)
    if (!arrayMatch) throw new Error('Could not find the `players` array in players.js')

    const formatMatch = source.match(/function\s+formatPrice\s*\([\s\S]*?\n\}/)
    if (!formatMatch) throw new Error('Could not find `formatPrice` in players.js')

    const players = new Function(`return ${arrayMatch[1]}`)()
    const formatPrice = new Function(`${formatMatch[0]}; return formatPrice;`)()
    return { players, formatPrice }
}

// Mirrors the template literal inside renderPlayers() in players.js. The
// data-label attributes are what the mobile card layout in players.css reads.
const renderRow = (player, formatPrice) =>
    `                <tr>
                    <td data-label="Name">${esc(player.name)}</td>
                    <td data-label="Country">${esc(player.country)}</td>
                    <td data-label="Role"><span class="role-badge">${esc(player.role)}</span></td>
                    <td class="price" data-label="Base Price">${esc(formatPrice(player.basePrice))}</td>
                </tr>`

const run = async () => {
    const [playersSource, html] = await Promise.all([
        readFile(PLAYERS_JS, 'utf8'),
        readFile(PLAYERS_HTML, 'utf8')
    ])

    const { players, formatPrice } = extract(playersSource)
    const rows = players.map((p) => renderRow(p, formatPrice)).join('\n')
    const block = `${START}\n${rows}\n            ${END}`

    // Idempotent: replace a previously generated block if one is there,
    // otherwise fill the empty <tbody> on the first run.
    let next
    if (html.includes(START)) {
        next = html.replace(new RegExp(`${escapeRe(START)}[\\s\\S]*?${escapeRe(END)}`), block)
    } else {
        const tbody = /(<tbody id="playersTable">)([\s\S]*?)(<\/tbody>)/
        if (!tbody.test(html)) throw new Error('Could not find <tbody id="playersTable"> in players.html')
        next = html.replace(tbody, `$1\n\n            ${block}\n\n        $3`)
    }

    if (next === html) {
        console.log(`[players-table] already up to date (${players.length} players)`)
        return
    }

    await writeFile(PLAYERS_HTML, next, 'utf8')
    console.log(`[players-table] wrote ${players.length} rows into players.html`)
}

function escapeRe(s) {
    return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}

run().catch((err) => {
    console.error('[players-table] failed:', err.message)
    process.exit(1)
})
